def _config_value(ctx, nodepath, name):
    try:
        provider = ctx.ServiceManager.createInstanceWithContext(
            "com.sun.star.configuration.ConfigurationProvider", ctx
        )
        arg = uno.createUnoStruct("com.sun.star.beans.PropertyValue")
        arg.Name = "nodepath"
        arg.Value = nodepath
        access = provider.createInstanceWithArguments(
            "com.sun.star.configuration.ConfigurationAccess", (arg,)
        )
        return access.getByName(name) or ""
    except Exception:
        return ""


def ui_language(ctx) -> str:
    """Two-letter code of LibreOffice's UI language. An empty ooLocale
    means "same as the system", so fall back to the system UI locale, then
    $LANG."""
    locale = (
        _config_value(ctx, "/org.openoffice.Setup/L10N", "ooLocale")
        or _config_value(ctx, "/org.openoffice.System/L10N", "UILocale")
        or os.environ.get("LC_ALL") or os.environ.get("LANG") or "en"
    )
    return locale.replace("_", "-").split("-")[0].split(".")[0].lower() or "en"


def translate(lang: str, key: str, **fmt) -> str:
    """Translator without a component context (e.g. on a worker thread)."""
    text = STRINGS.get(lang, STRINGS["en"]).get(key) or STRINGS["en"][key]
    return text.format(**fmt) if fmt else text


def is_no_model(exc) -> bool:
    """True for the "no model installed" condition (model_select.NoModelError)."""
    return type(exc).__name__ == "NoModelError"


class Translator:
    def __init__(self, ctx):
        self.lang = ui_language(ctx)
        self.table = STRINGS.get(self.lang, STRINGS["en"])

    def __call__(self, key, **fmt):
        text = self.table.get(key) or STRINGS["en"][key]
        return text.format(**fmt) if fmt else text

    def no_model_alert(self) -> str:
        """The whole alert shown when no model is available."""
        return self("no_model_title") + "\n" + self("no_model_text")

    def error_text(self, exc) -> str:
        """What the panel shows for a failed request: the no-model alert,
        or the usual "Error: ..." line."""
        return self.no_model_alert() if is_no_model(exc) else self("error", error=exc)
